def sumar(a, b, c, d, e): return a + b + c + d + e
def restar(a, b, c, d, e): return a - b - c - d - e
def multiplicar(a, b, c, d, e): return a * b * c * d * e
def dividir(a, b, c, d, e): return a / b / c / d / e

n1, n2, n3, n4, n5 = 5, 4, 3, 2, 1
print(f"Suma: {sumar(n1, n2, n3, n4, n5)}")
print(f"Resta: {restar(n1, n2, n3, n4, n5)}")
print(f"Multiplicación: {multiplicar(n1, n2, n3, n4, n5)}")
print(f"División: {dividir(n1, n2, n3, n4, n5)}")